# --- ставки, за които справочникът изрично казва, че не са потвърдени -------
NEPOTVARDENI = [
    ("прагът за социални разходи в евро",
     r"Същият праг \*\*в евро за 2026 г\.\*\* \| \*\*липсва\*\*[^|]*\|[^|]*\| \*\*за потвърждение\*\*",
     "M.PRAG_SOTSIALNI_RAZHODI"),
]


def main():
    print(f"Сверка: {os.path.relpath(STAVKI, os.path.join(HERE, '..'))}")
    print("=" * 78)
    padnali = []
    for proverka in PROVERKI:
        ime, shablon, v_modela = proverka[:3]
        dopusk = proverka[3] if len(proverka) > 3 else DOPUSK
        v_spravochnika = izvadi(shablon, ime)
        if v_spravochnika is None:
            print(f"  НЕНАМЕРЕНА  {ime}")
            print("              справочникът не съдържа стойност по този шаблон — "
                  "или е променен, или редът е преструктуриран")
            padnali.append(ime)
            continue
        if abs(v_spravochnika - v_modela) > dopusk:
            print(f"  РАЗМИНАВА   {ime}")
            print(f"              stavki.md: {v_spravochnika} | trz_model.py: {v_modela}")
            padnali.append(ime)
        else:
            print(f"  ок          {ime:56} {v_spravochnika}")

    print()
    for ime, shablon, konstanta in NEPOTVARDENI:
        if re.search(shablon, TEKST):
            print(f"  ок          {ime} — все още е маркирана `за потвърждение`;")
            print(f"              {konstanta} е работна хипотеза, находките от нея са "
                  f"`за проверка`")
        else:
            print(f"  ПРОМЯНА     {ime}")
            print(f"              статусът в справочника вече не е `за потвърждение`. "
                  f"Ако е потвърдена — свери {konstanta} и махни го от този списък.")
            padnali.append(ime)

    print("=" * 78)
    if padnali:
        print(f"ПАДНА: {len(padnali)} от {len(PROVERKI) + len(NEPOTVARDENI)}")
        print("Ставка в справочника се е разминала с модела на теста. Оправи "
              "trz_model.py, не обратното — справочникът е източникът на истина.")
        return 1
    print(f"OK: {len(PROVERKI) + len(NEPOTVARDENI)} ставки съвпадат със справочника")
    return 0


if __name__ == "__main__":
    sys.exit(main())
